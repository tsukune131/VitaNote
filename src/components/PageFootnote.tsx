import { SourcesLink } from './SourcesSheet';

/**
 * タブの末尾に常設する1行。
 *
 * 医師への相談を促し(ガイドライン1.4.1の2つ目の箇条書き)、出典への入口を
 * 無条件に確保する。カードの中に置かないのは、記録が0件のときにカードそのものが
 * 描かれないため — 審査に使われる端末はまさにその状態で、条件付きの配置だと
 * 「出典への入口が1つも無いタブ」ができてしまう。
 *
 * リンクの文言は、審査への返信で申告した「この画面の数値について」と一字一句そろえる。
 */
export function PageFootnote() {
  return (
    <p className="page-footnote">
      数値は推定の目安です。減量・食事制限・運動は体調に応じて医師にご相談ください。
      <SourcesLink label="この画面の数値について" />
    </p>
  );
}
